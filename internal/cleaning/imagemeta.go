// DetectImageFormat sniffs the container format of data, returning "png",
// "jpeg", "webp" or "unknown" (mirrors detect_format()).
func DetectImageFormat(data []byte) string {
	if bytes.HasPrefix(data, pngSig) {
		return "png"
	}
	if bytes.HasPrefix(data, jpegSOI) {
		return "jpeg"
	}
	if len(data) >= 12 && bytes.Equal(data[:4], webpRIFF) && bytes.Equal(data[8:12], webpSIG) {
		return "webp"
	}
	return "unknown"
}

