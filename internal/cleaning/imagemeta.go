// InspectImage inspects an image file and returns the report, mirroring
// inspect_image(path, synthid_dir=None). synthidDir may be empty to fall back
// to the REVERSE_SYNTHID_DIR environment variable.
func InspectImage(path string, synthidDir string) (ImageInspectReport, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return ImageInspectReport{}, err
	}
	format := DetectImageFormat(data)
	var hasC2PA, hasAI bool
	var findings []string
	switch format {
	case "png":
		hasC2PA, hasAI, findings = inspectPNG(data)
	case "jpeg":
		hasC2PA, hasAI, findings = inspectJPEG(data)
	case "webp":
		hasC2PA, hasAI, findings = inspectWebP(data)
	default:
		hasC2PA, hasAI, findings = false, false, []string{"unsupported format (PNG/JPEG/WebP)"}
	}

	notes := []string{}
	if format == "unknown" {
		notes = append(notes, "format not fully inspected; only PNG/JPEG are supported")
	}

	tools := RunOptionalTools(path)
	if ct, ok := tools["c2patool"].(map[string]interface{}); ok {
		if hm, ok := ct["has_manifest"].(bool); ok && hm {
			hasC2PA = true
			findings = append(findings, "c2patool reports a C2PA-related manifest")
		}
	}

	return ImageInspectReport{
		Path:          path,
		Format:        format,
		HasC2PA:       hasC2PA,
		HasAIMetadata: hasAI,
		Findings:      findings,
		Tools:         tools,
		Synthid:       runSynthidScore(path, synthidDir),
		Notes:         notes,
	}, nil
}

// CleanImageOptions mirrors clean_image()'s keyword arguments. Numeric and
// boolean options use pointers so an explicitly passed zero/false is honored
// exactly like a Python kwarg: nil means "omitted" and applies the Python
// default (StripAllMetadata=true, CtrlregenStrength=0.25, CtrlregenSteps=50,
// CtrlregenTimeout=3600, MarkdiffusionStrength=0.3, MarkdiffusionSize=512,
// MarkdiffusionSteps=50, MarkdiffusionTimeout=3600). The F64Ptr/IntPtr/
// BoolPtr helpers keep call sites readable.
type CleanImageOptions struct {
	StripAllMetadata      *bool
	SynthidDir            string
	RemovePixel           string // "", "ctrlregen", "diffusion"
	CtrlregenDir          string
	CtrlregenStrength     *float64
	CtrlregenSteps        *int
	CtrlregenDevice       string
	CtrlregenSeed         *int
	CtrlregenTimeout      *int
	MarkdiffusionDir      string
	MarkdiffusionStrength *float64
	MarkdiffusionModel    string
	MarkdiffusionSize     *int
	MarkdiffusionSteps    *int
	MarkdiffusionDevice   string
	MarkdiffusionTimeout  *int
}

// BoolPtr returns a pointer to v.
func BoolPtr(v bool) *bool { return &v }

// F64Ptr returns a pointer to v.
func F64Ptr(v float64) *float64 { return &v }

// IntPtr returns a pointer to v.
func IntPtr(v int) *int { return &v }

func derefBool(p *bool, def bool) bool {
	if p != nil {
		return *p
	}
	return def
}

func derefF64(p *float64, def float64) float64 {
	if p != nil {
		return *p
	}
	return def
}

func derefInt(p *int, def int) int {
	if p != nil {
		return *p
	}
	return def
}

// errString mirrors str(pixel_removal.get('error', 'unknown error')).
func errString(v interface{}) string {
	if s, ok := v.(string); ok {
		return s
	}
	return "unknown error"
}

// CleanImage cleans metadata from the image at src, writes the result to dest
// and returns the result dict, mirroring clean_image(path, dest, **kw). The
// dict keys are: input, output, format, actions, bytes_in, bytes_out,
// still_has_c2pa, still_has_ai_metadata, post_findings, synthid_before,
// synthid_after, pixel_removal (pixel_removal is nil when no pixel removal
// was requested).
func CleanImage(src, dest string, opts CleanImageOptions) (map[string]interface{}, error) {
	// Python keyword defaults for nil fields (see CleanImageOptions).
	stripAll := derefBool(opts.StripAllMetadata, true)
	ctrlregenStrength := derefF64(opts.CtrlregenStrength, 0.25)
	ctrlregenSteps := derefInt(opts.CtrlregenSteps, 50)
	ctrlregenTimeout := derefInt(opts.CtrlregenTimeout, 3600)
	markdiffusionStrength := derefF64(opts.MarkdiffusionStrength, 0.3)
	markdiffusionSize := derefInt(opts.MarkdiffusionSize, 512)
	markdiffusionSteps := derefInt(opts.MarkdiffusionSteps, 50)
	markdiffusionTimeout := derefInt(opts.MarkdiffusionTimeout, 3600)

	synthidBefore := runSynthidScore(src, opts.SynthidDir)

	data, err := os.ReadFile(src)
	if err != nil {
		return nil, err
	}
	format := DetectImageFormat(data)

	var cleaned []byte
	var actions []string
	switch format {
	case "png":
		cleaned, actions, err = stripPNG(data, stripAll)
	case "jpeg":
		cleaned, actions, err = stripJPEG(data, stripAll)
	case "webp":
		cleaned, actions, err = stripWebP(data, stripAll)
	default:
		return nil, fmt.Errorf("unsupported format: %s", format)
	}
	if err != nil {
		return nil, err
	}
	if err := SafeWriteBytes(dest, cleaned); err != nil {
		return nil, err
	}

	if exiftool := Which("exiftool"); exiftool != "" && stripAll {
		args := []string{exiftool, "-all=", "-overwrite_original", SafeArg(dest)}
		res := runCaptured(args, 60)
		if res.timedOut {
			actions = append(actions, fmt.Sprintf("exiftool failed: %s", pyTimeoutErr(args, 60)))
		} else if res.err != nil {
			actions = append(actions, fmt.Sprintf("exiftool failed: %s", res.err.Error()))
		} else {
			actions = append(actions, "exiftool -all= pass")
		}
	}

	var pixelRemoval map[string]interface{}
	if opts.RemovePixel != "" {
		switch opts.RemovePixel {
		case "ctrlregen":
			pixelRemoval = runCtrlregenClean(dest, dest, opts.CtrlregenDir, ctrlregenStrength, ctrlregenSteps, opts.CtrlregenDevice, opts.CtrlregenSeed, ctrlregenTimeout)
			if avail, _ := pixelRemoval["available"].(bool); avail {
				actions = append(actions, fmt.Sprintf("CtrlRegen pixel removal (strength %s)", pyFloatStr(ctrlregenStrength)))
			} else {
				actions = append(actions, fmt.Sprintf("CtrlRegen pixel removal skipped: %s", errString(pixelRemoval["error"])))
			}
		case "diffusion":
			pixelRemoval = runMarkdiffusionPurify(dest, dest, opts.MarkdiffusionDir, opts.MarkdiffusionModel, opts.MarkdiffusionDevice, markdiffusionStrength, markdiffusionSize, markdiffusionSteps, markdiffusionTimeout)
			if avail, _ := pixelRemoval["available"].(bool); avail {
				actions = append(actions, fmt.Sprintf("DiffusionPurification pixel removal (strength %s)", pyFloatStr(markdiffusionStrength)))
			} else {
				actions = append(actions, fmt.Sprintf("DiffusionPurification pixel removal skipped: %s", errString(pixelRemoval["error"])))
			}
		default:
			return nil, fmt.Errorf("unknown pixel remover: %s", opts.RemovePixel)
		}
	}

	after, err := InspectImage(dest, opts.SynthidDir)
	if err != nil {
		return nil, err
	}
	fi, err := os.Stat(dest)
	if err != nil {
		return nil, err
	}

	return map[string]interface{}{
		"input":                 src,
		"output":                dest,
		"format":                format,
		"actions":               actions,
		"bytes_in":              len(data),
		"bytes_out":             fi.Size(),
		"still_has_c2pa":        after.HasC2PA,
		"still_has_ai_metadata": after.HasAIMetadata,
		"post_findings":         after.Findings,
		"synthid_before":        synthidBefore,
		"synthid_after":         after.Synthid,
		"pixel_removal":         pixelRemoval,
	}, nil
}
