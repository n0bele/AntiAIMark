// containsAny mirrors the Python _contains_any: it reports which needles
// occur (case-insensitively) in blob, in needle order, using the original
// needle spelling. Python's bytes.lower() folds only ASCII A-Z, so
// asciiLowerBytes matches it exactly; bytes.ToLower would additionally fold
// non-ASCII UTF-8 runs and could create hits Python cannot produce.
func containsAny(blob []byte, needles [][]byte) []string {
	lower := asciiLowerBytes(blob)
	var found []string
	for _, n := range needles {
		if bytes.Contains(lower, asciiLowerBytes(n)) {
			found = append(found, string(n))
		}
	}
	return found
}

// asciiLowerBytes lowercases ASCII A-Z only (Python bytes.lower()).
func asciiLowerBytes(b []byte) []byte {
	out := append([]byte{}, b...)
	for i, c := range out {
		if c >= 'A' && c <= 'Z' {
			out[i] = c + ('a' - 'A')
		}
	}
	return out
}

// pyBytesRepr mirrors Python's repr() of a bytes object (e.g. b'\x89PNG').
func pyBytesRepr(b []byte) string {
	var sb strings.Builder
	sb.WriteString("b'")
	for _, c := range b {
		switch {
		case c == '\\':
			sb.WriteString(`\\`)
		case c == '\'':
			sb.WriteString(`\'`)
		case c == '\n':
			sb.WriteString(`\n`)
		case c == '\r':
			sb.WriteString(`\r`)
		case c == '\t':
			sb.WriteString(`\t`)
		case c >= 0x20 && c < 0x7f:
			sb.WriteByte(c)
		default:
			fmt.Fprintf(&sb, `\x%02x`, c)
		}
	}
	sb.WriteByte('\'')
	return sb.String()
}

// truncateUTF8 mirrors Python str[:n] (character-based truncation) without
// ever splitting a UTF-8 sequence.
func truncateUTF8(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n])
}

// splitLines mirrors Python str.splitlines() for the \n / \r\n / \r cases
// that external tool output produces.
func splitLines(s string) []string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")
	return strings.Split(s, "\n")
}

// sliceFirstStr returns at most the first n elements of s.
func sliceFirstStr(s []string, n int) []string {
	if len(s) > n {
		return s[:n]
	}
	return s
}

// pyFloatStr formats a float like Python's str(): 0.25 -> "0.25", 1.0 -> "1.0".
func pyFloatStr(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func inspectPNG(data []byte) (bool, bool, []string) {
	findings := []string{}
	hasC2PA := false
	hasAI := false
	if !bytes.HasPrefix(data, pngSig) {
		return false, false, []string{"not a PNG"}
	}
	pos := 8
	for pos+8 <= len(data) {
		length := int(binary.BigEndian.Uint32(data[pos : pos+4]))
		ctype := data[pos+4 : pos+8]
		chunkStart := pos + 8
		chunkEnd := chunkStart + length
		if chunkEnd+4 > len(data) {
			findings = append(findings, fmt.Sprintf("truncated chunk %s", pyBytesRepr(ctype)))
			break
		}
		payload := data[chunkStart:chunkEnd]
		// string(ctype) is exactly a latin-1 decode (byte -> rune 1:1).
		name := string(ctype)
		// Private/ancillary chunks sometimes used for JUMBF/C2PA
		if bytes.Equal(ctype, []byte("caBX")) || bytes.Equal(ctype, []byte("juMB")) || bytes.Equal(ctype, []byte("jumb")) || bytes.HasPrefix(ctype, []byte("c2")) {
			hasC2PA = true
			findings = append(findings, fmt.Sprintf("PNG chunk %s (possible C2PA container)", name))
		}
		if bytes.Equal(ctype, []byte("tEXt")) || bytes.Equal(ctype, []byte("zTXt")) || bytes.Equal(ctype, []byte("iTXt")) || bytes.Equal(ctype, []byte("eXIf")) {
			hits := containsAny(payload, aiPlusC2paMarkers)
			if len(hits) > 0 {
				hasAI = true
				for _, h := range hits {
					hl := strings.ToLower(h)
					if hl == "c2pa" || hl == "contentcredentials" || hl == "jumb" {
						hasC2PA = true
					}
				}
				findings = append(findings, fmt.Sprintf("PNG %s: %s", name, strings.Join(sliceFirstStr(hits, 8), ", ")))
			}
		}
		if bytes.Equal(ctype, []byte("IEND")) {
			break
		}
		pos = chunkEnd + 4 // skip CRC
	}
	// Whole-file scan fallback
	whole := containsAny(data, c2paMarkers)
	if len(whole) > 0 && !hasC2PA {
		hasC2PA = true
		findings = append(findings, fmt.Sprintf("byte-scan C2PA markers: %s", strings.Join(sliceFirstStr(whole, 6), ", ")))
	}
	return hasC2PA, hasAI || hasC2PA, findings
}

func inspectJPEG(data []byte) (bool, bool, []string) {
	findings := []string{}
	hasC2PA := false
	hasAI := false
	if !bytes.HasPrefix(data, jpegSOI) {
		return false, false, []string{"not a JPEG"}
	}
	i := 2
	n := len(data)
	for i+4 <= n {
		if data[i] != 0xFF {
			i++
			continue
		}
		// skip fill
		for i < n && data[i] == 0xFF {
			i++
		}
		if i >= n {
			break
		}
		marker := data[i]
		i++
		if marker == 0xD8 || marker == 0xD9 { // SOI/EOI
			continue
		}
		if marker == 0xDA { // SOS — image data follows
			break
		}
		if marker >= 0xD0 && marker <= 0xD7 { // RSTn
			continue
		}
		if i+2 > n {
			break
		}
		seglen := int(binary.BigEndian.Uint16(data[i : i+2]))
		if seglen < 2 || i+seglen > n {
			findings = append(findings, fmt.Sprintf("bad segment length at marker 0x%02X", marker))
			break
		}
		payload := data[i+2 : i+seglen]
		i += seglen

		// APP11 (0xEB) often holds JUMBF/C2PA
		if marker == 0xEB {
			hasC2PA = true
			findings = append(findings, "JPEG APP11 segment (JUMBF/C2PA common)")
		}
		if marker == 0xE1 || marker == 0xE2 || marker == 0xED || marker == 0xEE || marker == 0xEB { // APP1,2,13,14,11
			hits := containsAny(payload, aiPlusC2paMarkers)
			if len(hits) > 0 {
				hasAI = true
				for _, h := range hits {
					hl := strings.ToLower(h)
					if hl == "c2pa" || hl == "contentcredentials" || hl == "jumb" || hl == "contentauth" {
						hasC2PA = true
					}
				}
				findings = append(findings, fmt.Sprintf("JPEG APP%d: %s", int(marker)-0xE0, strings.Join(sliceFirstStr(hits, 8), ", ")))
			}
		}
	}

	whole := containsAny(data, c2paMarkers)
	if len(whole) > 0 && !hasC2PA {
		hasC2PA = true
		findings = append(findings, fmt.Sprintf("byte-scan C2PA markers: %s", strings.Join(sliceFirstStr(whole, 6), ", ")))
	}
	return hasC2PA, hasAI || hasC2PA, findings
}

type webpChunk struct {
	fourcc  []byte
	payload []byte
	padding []byte
}

func webpChunks(data []byte) ([]webpChunk, []string) {
	if DetectImageFormat(data) != "webp" {
		return nil, []string{"not a WebP"}
	}

	notes := []string{}
	declaredSize := int(binary.LittleEndian.Uint32(data[4:8]))
	if declaredSize+8 != len(data) {
		notes = append(notes, fmt.Sprintf("RIFF size mismatch: header=%d actual=%d", declaredSize+8, len(data)))
	}

	var chunks []webpChunk
	pos := 12
	for pos+8 <= len(data) {
		fourcc := data[pos : pos+4]
		length := int(binary.LittleEndian.Uint32(data[pos+4 : pos+8]))
		payloadStart := pos + 8
		payloadEnd := payloadStart + length
		paddedEnd := payloadEnd + (length & 1)
		if paddedEnd > len(data) {
			name := string(fourcc)
			notes = append(notes, fmt.Sprintf("truncated WebP chunk %s", name))
			break
		}
		chunks = append(chunks, webpChunk{fourcc, data[payloadStart:payloadEnd], data[payloadEnd:paddedEnd]})
		pos = paddedEnd
	}
	if pos != len(data) && !anyTruncated(notes) {
		notes = append(notes, fmt.Sprintf("trailing WebP bytes: %d", len(data)-pos))
	}
	return chunks, notes
}

func anyTruncated(notes []string) bool {
	for _, note := range notes {
		if strings.Contains(note, "truncated") {
			return true
		}
	}
	return false
}

func inspectWebP(data []byte) (bool, bool, []string) {
	chunks, findings := webpChunks(data)
	if len(chunks) == 0 && len(findings) == 1 && findings[0] == "not a WebP" {
		return false, false, findings
	}

	hasC2PA := false
	hasAI := false
	for _, ch := range chunks {
		name := string(ch.fourcc)
		if bytes.Equal(bytes.ToUpper(ch.fourcc), []byte("C2PA")) {
			hasC2PA = true
			hasAI = true
			findings = append(findings, "WebP C2PA chunk")
			continue
		}
		if bytes.Equal(ch.fourcc, []byte("XMP ")) || bytes.Equal(ch.fourcc, []byte("EXIF")) {
			hits := containsAny(ch.payload, aiPlusC2paMarkers)
			if len(hits) > 0 {
				hasAI = true
				for _, hit := range hits {
					hl := strings.ToLower(hit)
					if hl == "c2pa" || hl == "contentcredentials" || hl == "jumb" || hl == "contentauth" {
						hasC2PA = true
					}
				}
				findings = append(findings, fmt.Sprintf("WebP %s: %s", name, strings.Join(sliceFirstStr(hits, 8), ", ")))
			}
		}
	}
	return hasC2PA, hasAI || hasC2PA, findings
}

var protectedPNGChunks = map[string]bool{
	"IHDR": true, "IDAT": true, "IEND": true, "PLTE": true, "tRNS": true,
	"gAMA": true, "pHYs": true, "sRGB": true, "cHRM": true, "iCCP": true,
}

func stripPNG(data []byte, stripAllText bool) ([]byte, []string, error) {
	if !bytes.HasPrefix(data, pngSig) {
		return nil, nil, fmt.Errorf("not PNG")
	}
	actions := []string{}
	out := make([]byte, 0, len(data))
	out = append(out, pngSig...)
	pos := 8
	for pos+8 <= len(data) {
		length := int(binary.BigEndian.Uint32(data[pos : pos+4]))
		ctype := data[pos+4 : pos+8]
		chunkStart := pos + 8
		chunkEnd := chunkStart + length
		if chunkEnd+4 > len(data) {
			break
		}
		payload := data[chunkStart:chunkEnd]
		crcBytes := data[chunkEnd : chunkEnd+4]
		pos = chunkEnd + 4
		name := string(ctype)

		drop := false
		if bytes.Equal(ctype, []byte("eXIf")) || bytes.Equal(ctype, []byte("caBX")) || bytes.HasPrefix(ctype, []byte("c2")) {
			drop = true
			actions = append(actions, fmt.Sprintf("drop chunk %s", name))
		} else if bytes.Equal(ctype, []byte("tEXt")) || bytes.Equal(ctype, []byte("zTXt")) || bytes.Equal(ctype, []byte("iTXt")) {
			if stripAllText || len(containsAny(payload, aiPlusC2paMarkers)) > 0 {
				drop = true
				actions = append(actions, fmt.Sprintf("drop chunk %s", name))
			}
		} else if len(containsAny(append(append([]byte{}, ctype...), payload...), c2paMarkers)) > 0 && !protectedPNGChunks[string(ctype)] {
			drop = true
			actions = append(actions, fmt.Sprintf("drop chunk %s (C2PA marker in payload)", name))
		}

		if !drop {
			var hdr [4]byte
			binary.BigEndian.PutUint32(hdr[:], uint32(length))
			out = append(out, hdr[:]...)
			out = append(out, ctype...)
			out = append(out, payload...)
			out = append(out, crcBytes...)
		}
		if bytes.Equal(ctype, []byte("IEND")) {
			break
		}
	}
	if len(actions) == 0 {
		actions = append(actions, "no PNG metadata chunks removed (already clean or none matched)")
	}
	return out, actions, nil
}

func stripJPEG(data []byte, stripAllApp bool) ([]byte, []string, error) {
	if !bytes.HasPrefix(data, jpegSOI) {
		return nil, nil, fmt.Errorf("not JPEG")
	}
	actions := []string{}
	out := make([]byte, 0, len(data))
	out = append(out, jpegSOI...)
	i := 2
	n := len(data)
	for i < n {
		if data[i] != 0xFF {
			// unexpected; copy rest
			out = append(out, data[i:]...)
			actions = append(actions, "copied remainder after non-marker byte")
			break
		}
		for i < n && data[i] == 0xFF {
			i++
		}
		if i >= n {
			break
		}
		marker := data[i]
		i++

		if marker == 0xD9 { // EOI
			out = append(out, 0xFF, 0xD9)
			break
		}
		if marker == 0xD8 { // nested SOI?
			continue
		}
		if marker >= 0xD0 && marker <= 0xD7 {
			out = append(out, 0xFF, marker)
			continue
		}
		if marker == 0xDA { // SOS — copy through end
			// need length of SOS header then entropy-coded data to EOI
			if i+2 > n {
				break
			}
			_ = binary.BigEndian.Uint16(data[i : i+2])
			// Reconstruct: FF DA + rest of file
			out = append(out, 0xFF, 0xDA)
			out = append(out, data[i:]...)
			actions = append(actions, "preserved entropy-coded scan (SOS→EOF)")
			break
		}

		if i+2 > n {
			break
		}
		seglen := int(binary.BigEndian.Uint16(data[i : i+2]))
		if seglen < 2 || i+seglen > n {
			out = append(out, data[i-2:]...) // best effort
			actions = append(actions, "truncated segment; copied remainder")
			break
		}
		payload := data[i+2 : i+seglen]
		nextI := i + seglen

		// APP0 is JFIF — keep for compatibility unless full strip of all APP
		keep := false
		drop := false
		if marker >= 0xE0 && marker <= 0xEF { // APPn
			if marker == 0xEB { // APP11 JUMBF/C2PA
				drop = true
				actions = append(actions, "drop APP11 (C2PA/JUMBF)")
			} else if stripAllApp && marker != 0xE0 {
				// keep APP0 (JFIF) by default
				drop = true
				actions = append(actions, fmt.Sprintf("drop APP%d", int(marker)-0xE0))
			} else if len(containsAny(payload, aiPlusC2paMarkers)) > 0 {
				drop = true
				actions = append(actions, fmt.Sprintf("drop APP%d (AI/C2PA markers)", int(marker)-0xE0))
			} else {
				keep = true
			}
		} else if marker == 0xFE { // COM
			drop = true
			actions = append(actions, "drop COM comment")
		} else {
			keep = true
		}

		if keep && !drop {
			out = append(out, 0xFF, marker)
			out = append(out, data[i:i+seglen]...)
		}
		i = nextI
	}

	if len(actions) == 0 {
		actions = append(actions, "no JPEG APP segments removed")
	}
	return out, actions, nil
}

func stripWebP(data []byte, stripAllMetadata bool) ([]byte, []string, error) {
	chunks, notes := webpChunks(data)
	if len(chunks) == 0 && len(notes) == 1 && notes[0] == "not a WebP" {
		return nil, nil, fmt.Errorf("not WebP")
	}
	if len(notes) > 0 {
		return nil, nil, fmt.Errorf("malformed WebP: %s", strings.Join(notes, "; "))
	}

	actions := []string{}
	type keptChunk struct {
		fourcc  []byte
		payload []byte
		padding []byte
	}
	var kept []keptChunk
	removedFlags := 0
	metadataFlags := map[string]int{"ICCP": 0x20, "EXIF": 0x08, "XMP ": 0x04}

	for _, ch := range chunks {
		drop := bytes.Equal(bytes.ToUpper(ch.fourcc), []byte("C2PA"))
		if _, ok := metadataFlags[string(ch.fourcc)]; ok {
			drop = stripAllMetadata || len(containsAny(ch.payload, aiPlusC2paMarkers)) > 0
		}
		if drop {
			name := string(ch.fourcc)
			actions = append(actions, fmt.Sprintf("drop WebP chunk %s", name))
			removedFlags |= metadataFlags[string(ch.fourcc)]
		} else {
			kept = append(kept, keptChunk{ch.fourcc, ch.payload, ch.padding})
		}
	}

	body := make([]byte, 0, len(data))
	body = append(body, webpSIG...)
	for _, ch := range kept {
		payload := ch.payload
		if bytes.Equal(ch.fourcc, []byte("VP8X")) && len(payload) >= 1 && removedFlags != 0 {
			payload = append([]byte{payload[0] &^ byte(removedFlags)}, payload[1:]...)
		}
		body = append(body, ch.fourcc...)
		var sz [4]byte
		binary.LittleEndian.PutUint32(sz[:], uint32(len(payload)))
		body = append(body, sz[:]...)
		body = append(body, payload...)
		if len(payload)&1 == 1 {
			body = append(body, ch.padding...)
		}
	}

	if len(actions) == 0 {
		actions = append(actions, "no WebP metadata chunks removed (already clean or none matched)")
	}
	var sz [4]byte
	binary.LittleEndian.PutUint32(sz[:], uint32(len(body)))
	out := append([]byte{}, webpRIFF...)
	out = append(out, sz[:]...)
	out = append(out, body...)
	return out, actions, nil
}

// captResult mirrors what Python's subprocess.CompletedProcess holds plus a
